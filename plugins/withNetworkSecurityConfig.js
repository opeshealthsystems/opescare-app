/**
 * Android TLS certificate pinning for the OpesCare API (opescare.com and every
 * subdomain), via res/xml/network_security_config.xml.
 *
 * We pin the SPKI SHA-256 of Let's Encrypt ROOTS, never the leaf, so the
 * 90-day certificate renewals never break the app:
 *   - ISRG Root X1 (RSA)    expires 2035-06-04
 *   - ISRG Root X2 (ECDSA)  expires 2040-09-17
 *   - ISRG Root YE (ECDSA)  the new LE hierarchy served in the live chain
 *     (YE2 -> Root YE -> X2 cross-sign). Pinned too because devices whose
 *     trust store holds Root YE directly end the validated path there, not at X2.
 * Hashes computed 2026-10-18 from the live chain of opescare.com and from
 * letsencrypt.org/certs:
 *   openssl x509 -pubkey -noout | openssl pkey -pubin -outform der \
 *     | openssl dgst -sha256 -binary | openssl enc -base64
 *
 * The pin-set expires PIN_EXPIRATION: after that date pinning is off and
 * normal CA validation applies, so a pin mistake fails open instead of
 * bricking old installs. Refresh the date (and re-check the hashes) on each
 * release before then.
 *
 * Cleartext: once a network security config exists, Android ignores the
 * manifest's usesCleartextTraffic, so base-config mirrors the value
 * app.config.js derives (true only for the `local-api` http:// profile).
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const PIN_EXPIRATION = '2027-10-18';
const PINNED_DOMAIN = 'opescare.com';
const PINS = [
  { name: 'ISRG Root X1', sha256: 'C5+lpZ7tcVwmwQIMcRtPbsQtWLABXhQzejna0wHFr8M=' },
  { name: 'ISRG Root X2', sha256: 'diGVwiVYbubAI3RW4hB9xU8e/CH2GnkuvVFZE8zmgzI=' },
  { name: 'ISRG Root YE', sha256: 'sCkq5UWXjg+7mKu9lMhhYF5bGLsy7VI/UNW3tccdR7w=' },
];

function buildXml(cleartext) {
  const pins = PINS.map((p) => `      <!-- ${p.name} -->\n      <pin digest="SHA-256">${p.sha256}</pin>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNetworkSecurityConfig.js. Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="${cleartext}">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="true">${PINNED_DOMAIN}</domain>
    <pin-set expiration="${PIN_EXPIRATION}">
${pins}
    </pin-set>
  </domain-config>
</network-security-config>
`;
}

module.exports = function withNetworkSecurityConfig(config) {
  const cleartext = config.android?.usesCleartextTraffic === true;

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), buildXml(cleartext));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
};
